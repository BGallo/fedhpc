"""Compact LaTeX table: GA (memetic, GA-mid configuration) vs Gurobi on the 108
generated instances × λ ∈ {0.25, 0.5, 0.75}, GA seeds 42/1/7.

One row per (class, workload, N): 9 instances (3 loads × 3 io levels) × 3 λ =
27 cells, plus a total row. Per cell, the best known solution (BKS) is the
lowest g_λ found by Gurobi or any GA seed; gaps are 100 (g − BKS) / BKS, and 0
when BKS = 0 (trivial instances, f2^T = 0) and g = 0 (every run there reaches
it; the script fails otherwise).

Gurobi = the weighted-sum solve of results/generated_bench/bench_io_noreduc.jsonl
(4 threads, 600 s); GA = the validate_*gamid*.jsonl runs. Both sides report
the same four columns (mean g, gap to BKS, #BKS, total time); incumbent times
are not shown because Gurobi's were not recorded.

Labels: workload fedhpc -> W1, pos -> W2.

    uv run python scripts/table_ga_vs_gurobi.py [--out docs/tables/ga_vs_gurobi.tex]
"""
from __future__ import annotations

import argparse
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GB = ROOT / "results" / "generated_bench"
D = GB / "dispatch_study"
# GA-mid runs per seed: held-out split, tuning split (same configuration), trivial instances
SEEDS = {42: ("F_gamid_s42", "T_sl48p16g120_s42", "Triv_gamid_s42"),
         1: ("F_gamid_s1", "T_gamid_s1", "Triv_gamid_s1"),
         7: ("F_gamid_s7", "T_gamid_s7", "Triv_gamid_s7")}
WL = {"fedhpc": "W1", "pos": "W2"}
EPS = 1e-9


def load():
    bench = {(r := json.loads(l))["name"]: r for l in (GB / "bench_io_noreduc.jsonl").open()}
    ga: dict[tuple[str, str], dict[int, dict]] = defaultdict(dict)
    for seed, tags in SEEDS.items():
        for tag in tags:
            for line in (D / f"validate_{tag}.jsonl").open():
                r = json.loads(line)
                for lam, v in r["lams"].items():
                    ga[(r["name"], lam)][seed] = v
    assert len(ga) == 3 * len(bench), len(ga)
    cells = []
    for (name, lam), runs in ga.items():
        assert set(runs) == set(SEEDS), (name, lam)
        b = bench[name]
        gur = b["lams"][lam]["gurobi"]
        g_ga = [v["g"] for v in runs.values()]
        bks = min(gur["g"], *g_ga)

        def gap(g):
            if bks <= EPS:
                assert g <= EPS, (name, lam, g)
                return 0.0
            return 100 * (g - bks) / bks

        assert all(v["trace"] for v in runs.values()), (name, lam)
        cells.append(dict(
            cls=b["cls"], wl=b["workload"], n=b["count"], g_opt=gur["status"] == "optimal",
            g_g=gur["g"], g_gap=gap(gur["g"]), g_hit=gap(gur["g"]) <= 1e-4, g_t=gur["t"],
            # GA: seed means; a cell counts as a BKS hit when its best seed reaches it
            ga_g=st.mean(g_ga), ga_gap=st.mean(map(gap, g_ga)), ga_hit=gap(min(g_ga)) <= 1e-4,
            ga_t=st.mean(v["t"] for v in runs.values())))
    return cells


def row(cs) -> str:
    m = lambda k: st.mean(c[k] for c in cs)  # noqa: E731
    return " & ".join(f"{m(p + '_g'):.3f} & {m(p + '_gap'):.2f} & {sum(c[p + '_hit'] for c in cs)} & "
                      f"{m(p + '_t'):.1f}" for p in ("g", "ga"))


def table(cells) -> str:
    out = [r"""% Generated by scripts/table_ga_vs_gurobi.py -- do not edit by hand.
% Needs \usepackage{booktabs,multirow}.
\begin{table*}[t]
\centering\footnotesize
\setlength{\tabcolsep}{5pt}
\caption{Gurobi versus the GA on the 108 generated instances. Each row averages 27
cells: 9 instances (loads F/H/E $\times$ io levels L/M/H) $\times$
$\lambda\in\{0.25,0.5,0.75\}$. $\bar g$: mean objective $g_\lambda$. \emph{Gap}: gap to
the best known solution (BKS, the best $g_\lambda$ found by either method),
$100\,(g_\lambda-g_\lambda^{\mathrm{BKS}})/g_\lambda^{\mathrm{BKS}}$, taken as 0
when both are 0 (instances whose fastest schedule is free). \emph{\#BKS}: cells
where the method reaches the BKS (for the GA, with its best seed). $t$: mean
wall-clock time in seconds (4 threads each; Gurobi limit 600\,s per solve). GA
values are averages over 3 seeds. Gurobi proves optimality in @OPT@ of the 324
cells; the other @NOPT@ hit the time limit.}
\label{tab:ga-vs-gurobi}
\begin{tabular}{llrrrrrrrrr}
\toprule
 & & & \multicolumn{4}{c}{Gurobi} & \multicolumn{4}{c}{GA} \\
\cmidrule(lr){4-7}\cmidrule(lr){8-11}
Class & Wkl. & $N$ & $\bar g$ & Gap (\%) & \#BKS & $t$ & $\bar g$ & Gap (\%) & \#BKS & $t$ \\
\midrule"""]
    n_opt = sum(c["g_opt"] for c in cells)
    out[0] = out[0].replace("@OPT@", str(n_opt)).replace("@NOPT@", str(len(cells) - n_opt))
    groups = sorted({(c["cls"], WL[c["wl"]]) for c in cells})
    for gi, (cls, wl) in enumerate(groups):
        gc = [c for c in cells if c["cls"] == cls and WL[c["wl"]] == wl]
        ns = sorted({c["n"] for c in gc})
        for j, n in enumerate(ns):
            lead = (rf"\multirow{{{len(ns)}}}{{*}}{{{cls}}} & \multirow{{{len(ns)}}}{{*}}{{{wl}}}"
                    if j == 0 else " & ")
            out.append(f"{lead} & {n} & {row([c for c in gc if c['n'] == n])} \\\\")
        if gi < len(groups) - 1:
            out.append(r"\cmidrule(lr){1-11}")
    out.append(r"\midrule")
    out.append(rf"\multicolumn{{3}}{{l}}{{All (324 cells)}} & {row(cells)} \\")
    out.append(r"""\bottomrule
\end{tabular}
\end{table*}
""")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "tables" / "ga_vs_gurobi.tex")
    args = ap.parse_args()
    cells = load()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(table(cells))
    print(f"{len(cells)} cells -> {args.out}")
    better = [c for c in cells if c["g_gap"] > 1e-4]
    print(f"cells where the GA beat Gurobi: {len(better)}",
          [(c["cls"], c["wl"], c["n"], round(c["g_gap"], 3), c["g_opt"]) for c in better])


if __name__ == "__main__":
    main()
